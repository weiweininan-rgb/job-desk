-- Application dates are a user-facing calendar value, so use the job tracker's
-- local timezone instead of the database session timezone when confirming a source job.
create or replace function public.confirm_job_source(p_job_source_id uuid)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  source_row public.job_sources;
  application_id bigint;
begin
  select * into source_row from public.job_sources where id = p_job_source_id and owner_id = auth.uid();
  if not found then raise exception '岗位不存在或无权访问'; end if;

  select id into application_id from public.applications where source_job_id = p_job_source_id;
  if application_id is not null then return application_id; end if;

  insert into public.applications (
    owner_id, source_job_id, company_name, position, location, application_date,
    status, notes, job_url, batch, is_chengdu, is_major_company
  ) values (
    auth.uid(), source_row.id, source_row.company_name, source_row.position, source_row.location,
    timezone('Asia/Shanghai', now())::date,
    '已投递', source_row.notes, source_row.apply_url, source_row.batch, source_row.is_chengdu, source_row.is_major_company
  ) returning id into application_id;

  update public.job_sources set status = 'converted', updated_at = now() where id = p_job_source_id;
  return application_id;
end;
$$;

create or replace function public.delete_application_and_restore_source(p_application_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  application_row public.applications;
  source_row public.job_sources;
begin
  select * into application_row
  from public.applications
  where id = p_application_id and owner_id = auth.uid();

  if not found then
    raise exception '申请记录不存在或无权删除';
  end if;

  if application_row.source_job_id is not null then
    select * into source_row
    from public.job_sources
    where id = application_row.source_job_id and owner_id = auth.uid();

    if found then
      update public.job_sources
      set status = 'pool', updated_at = now()
      where owner_id = auth.uid()
        and status = 'converted'
        and company_name = source_row.company_name
        and batch = source_row.batch
        and (
          (source_row.apply_url <> '' and apply_url = source_row.apply_url)
          or (source_row.apply_url = '' and source_row.article_url <> '' and article_url = source_row.article_url)
          or (source_row.apply_url = '' and source_row.article_url = '' and id = source_row.id)
        );
    end if;
  end if;

  delete from public.application_interviews where application_id = p_application_id;
  delete from public.applications where id = p_application_id;
end;
$$;

grant execute on function public.delete_application_and_restore_source(bigint) to authenticated;

alter table public.sync_runs
  add column if not exists read_count integer not null default 0;

alter table public.user_settings
  add column if not exists last_manual_synced_at timestamptz,
  add column if not exists last_auto_synced_at timestamptz,
  add column if not exists sync_in_progress_at timestamptz;

update public.user_settings
set last_auto_synced_at = last_synced_at
where last_auto_synced_at is null and last_synced_at is not null;

create or replace function public.claim_feishu_sync_slot(p_owner_id uuid)
returns boolean
language sql
security definer
set search_path = public
as 'with claimed as (
  insert into public.user_settings (owner_id, sync_in_progress_at)
  values (p_owner_id, now())
  on conflict (owner_id) do update
  set sync_in_progress_at = excluded.sync_in_progress_at
  where public.user_settings.sync_in_progress_at is null
    or public.user_settings.sync_in_progress_at < now() - make_interval(mins => 15)
  returning true
)
select coalesce((select true from claimed), false)';

create or replace function public.release_feishu_sync_slot(p_owner_id uuid)
returns void
language sql
security definer
set search_path = public
as E'
  update public.user_settings
  set sync_in_progress_at = null
  where owner_id = p_owner_id;
';

revoke all on function public.claim_feishu_sync_slot(uuid) from public;
revoke all on function public.release_feishu_sync_slot(uuid) from public;
grant execute on function public.claim_feishu_sync_slot(uuid) to service_role;
grant execute on function public.release_feishu_sync_slot(uuid) to service_role;
revoke all on function public.confirm_job_source(uuid) from public, anon;
revoke all on function public.delete_application_and_restore_source(bigint) from public, anon;
grant execute on function public.confirm_job_source(uuid) to authenticated;
grant execute on function public.delete_application_and_restore_source(bigint) to authenticated;
commit;

