-- Job Desk: ONLY for a new, empty Supabase public schema. Transactional.
-- Refuses an existing installation rather than overwriting data.
begin;
do $$ begin
  if exists (select 1 from information_schema.tables where table_schema='public' and table_type='BASE TABLE') then
    raise exception 'Initialize a NEW empty project, not an existing database';
  end if;
end $$;

create table public.job_sources (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users(id) on delete cascade,
  fingerprint text not null, company_name text not null, position text not null,
  batch text not null default '秋招正式批' check (batch in ('提前批','秋招正式批')),
  location text default '', apply_url text default '', article_url text default '', notes text default '',
  published_at text default '', source_updated_at text default '',
  is_chengdu boolean not null default false, is_major_company boolean not null default false,
  is_pinned boolean not null default false, is_deprioritized boolean not null default false,
  status text not null default 'pool' check(status in ('pool','pending_confirmation','converted','archived')),
  last_opened_at timestamptz, created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  unique(owner_id,fingerprint)
);
create table public.applications (
  id bigint primary key generated by default as identity,
  owner_id uuid not null references auth.users(id) on delete cascade,
  source_job_id uuid references public.job_sources(id) on delete set null,
  company_name text not null default '', position text not null default '',
  salary_range text default '', location text default '', job_url text default '', notes text default '',
  application_date date default timezone('Asia/Shanghai',now())::date,
  status text default '已投递', next_interview_date timestamp,
  batch text, is_chengdu boolean not null default false, is_major_company boolean not null default false,
  is_pinned boolean not null default false, is_abandoned boolean not null default false,
  created_at timestamptz default now(), updated_at timestamptz default now()
);
create unique index applications_source_job_unique on public.applications(source_job_id) where source_job_id is not null;
create table public.application_interviews (
  id bigint primary key generated by default as identity,
  application_id bigint not null references public.applications(id) on delete cascade,
  round text not null default '一面', scheduled_time timestamp, location text default '',
  status text default '待面试', notes text default '', process_type text default '面试',
  deadline timestamp, reminder_triggered boolean default false,
  created_at timestamptz default now(), updated_at timestamptz default now()
);
create table public.user_settings (
  owner_id uuid primary key references auth.users(id) on delete cascade,
  profile_keywords text[] not null default '{}', major_companies text[] not null default '{}',
  preferred_cities text[] not null default '{}',
  last_synced_at timestamptz, last_manual_synced_at timestamptz, last_auto_synced_at timestamptz,
  sync_in_progress_at timestamptz, updated_at timestamptz not null default now()
);
create table public.sync_runs (
  id uuid primary key default gen_random_uuid(), owner_id uuid not null references auth.users(id) on delete cascade,
  trigger text not null check(trigger in ('manual','scheduled')),
  status text not null check(status in ('success','failed','skipped')),
  created_count integer not null default 0, updated_count integer not null default 0,
  filtered_count integer not null default 0, unchanged_count integer not null default 0,
  read_count integer not null default 0, message text default '', created_at timestamptz not null default now()
);
create table public.feishu_connections (
  owner_id uuid primary key references auth.users(id) on delete cascade,
  refresh_token text not null, refresh_token_expires_at timestamptz, scope text,
  connected_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table public.feishu_oauth_states (
  state uuid primary key, owner_id uuid not null references auth.users(id) on delete cascade,
  expires_at timestamptz not null, created_at timestamptz not null default now()
);
alter table public.applications enable row level security;
alter table public.application_interviews enable row level security;
alter table public.job_sources enable row level security;
alter table public.user_settings enable row level security;
alter table public.sync_runs enable row level security;
alter table public.feishu_connections enable row level security;
alter table public.feishu_oauth_states enable row level security;
